"""Database access for hire enquiries.

SQLite is used when DATABASE_URL is not configured.  Production deployments
should set DATABASE_URL to a PostgreSQL connection string (for example, Neon).
"""

import os
import sqlite3
from contextlib import closing
from datetime import datetime, timezone
from typing import Any

import psycopg
from psycopg.rows import dict_row

DEFAULT_DB_PATH = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "n3thunt3r.db"
)


def _use_postgres() -> bool:
    return bool(os.getenv("DATABASE_URL"))


def _connect() -> Any:
    database_url = os.getenv("DATABASE_URL")
    if database_url:
        return psycopg.connect(database_url, row_factory=dict_row)

    connection = sqlite3.connect(os.getenv("DB_PATH") or DEFAULT_DB_PATH)
    connection.row_factory = sqlite3.Row
    return connection


def _placeholder() -> str:
    return "%s" if _use_postgres() else "?"


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def init_db() -> None:
    """Create the schema safely on every application startup."""
    with closing(_connect()) as conn, conn:
        if _use_postgres():
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS enquiries (
                    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id      BIGINT NOT NULL,
                    username     TEXT,
                    name         TEXT NOT NULL,
                    need         TEXT NOT NULL,
                    description  TEXT NOT NULL,
                    status       TEXT NOT NULL DEFAULT 'active',
                    created_at   TEXT NOT NULL,
                    cancelled_at TEXT
                )
                """
            )
        else:
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS enquiries (
                    id           INTEGER PRIMARY KEY AUTOINCREMENT,
                    user_id      INTEGER NOT NULL,
                    username     TEXT,
                    name         TEXT NOT NULL,
                    need         TEXT NOT NULL,
                    description  TEXT NOT NULL,
                    status       TEXT NOT NULL DEFAULT 'active',
                    created_at   TEXT NOT NULL,
                    cancelled_at TEXT
                )
                """
            )
        conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_enquiries_user ON enquiries(user_id)"
        )


def add_enquiry(
    user_id: int, username: str | None, name: str, need: str, description: str
) -> int:
    """Save a new enquiry and return its number."""
    placeholder = _placeholder()
    with closing(_connect()) as conn, conn:
        if _use_postgres():
            cursor = conn.execute(
                f"""
                INSERT INTO enquiries
                    (user_id, username, name, need, description, status, created_at)
                VALUES ({placeholder}, {placeholder}, {placeholder}, {placeholder},
                        {placeholder}, 'active', {placeholder})
                RETURNING id
                """,
                (user_id, username, name, need, description, _now()),
            )
            return int(cursor.fetchone()["id"])

        cursor = conn.execute(
            f"""
            INSERT INTO enquiries
                (user_id, username, name, need, description, status, created_at)
            VALUES ({placeholder}, {placeholder}, {placeholder}, {placeholder},
                    {placeholder}, 'active', {placeholder})
            """,
            (user_id, username, name, need, description, _now()),
        )
        return int(cursor.lastrowid)


def get_user_enquiries(user_id: int) -> list[dict]:
    """All enquiries (active and cancelled) for one user, newest first."""
    with closing(_connect()) as conn:
        rows = conn.execute(
            f"SELECT * FROM enquiries WHERE user_id = {_placeholder()} ORDER BY id DESC",
            (user_id,),
        ).fetchall()
    return [dict(row) for row in rows]


def get_enquiry(user_id: int, enquiry_id: int) -> dict | None:
    """One enquiry, but only if it belongs to this user."""
    placeholder = _placeholder()
    with closing(_connect()) as conn:
        row = conn.execute(
            f"SELECT * FROM enquiries WHERE id = {placeholder} AND user_id = {placeholder}",
            (enquiry_id, user_id),
        ).fetchone()
    return dict(row) if row else None


def count_active(user_id: int) -> int:
    placeholder = _placeholder()
    with closing(_connect()) as conn:
        row = conn.execute(
            f"SELECT COUNT(*) AS total FROM enquiries "
            f"WHERE user_id = {placeholder} AND status = 'active'",
            (user_id,),
        ).fetchone()
    return int(row["total"])


def cancel_enquiry(user_id: int, enquiry_id: int) -> bool:
    """Cancel one active enquiry. Returns True if something was cancelled."""
    placeholder = _placeholder()
    with closing(_connect()) as conn, conn:
        cursor = conn.execute(
            f"""
            UPDATE enquiries SET status = 'cancelled', cancelled_at = {placeholder}
            WHERE id = {placeholder} AND user_id = {placeholder} AND status = 'active'
            """,
            (_now(), enquiry_id, user_id),
        )
        return cursor.rowcount > 0


def cancel_all(user_id: int) -> list[int]:
    """Cancel every active enquiry for a user and return their numbers."""
    placeholder = _placeholder()
    with closing(_connect()) as conn, conn:
        rows = conn.execute(
            f"SELECT id FROM enquiries WHERE user_id = {placeholder} "
            "AND status = 'active' ORDER BY id",
            (user_id,),
        ).fetchall()
        ids = [int(row["id"]) for row in rows]
        if ids:
            conn.execute(
                f"""
                UPDATE enquiries SET status = 'cancelled', cancelled_at = {placeholder}
                WHERE user_id = {placeholder} AND status = 'active'
                """,
                (_now(), user_id),
            )
    return ids
